#!/usr/bin/env node
// Build step: convert the Commander X16 ZSM soundtrack into the VERA "VZM"
// PSG + YM2151 FM stream played when the FM daughterboard is fitted.
//
// Outputs:
//   generated/music.vzm   - the PSG+FM stream shipped as MUSIC.VZM on the HDV
//   generated/music_vzm.h - size / loop offset / tick count for src/audio.c
//
// The PSG-only stream (generated/music.psg, MUSIC.PSG) is produced separately
// by tools/zsm2psg.py and stays in the image for cards without an FM chip.
import fs from "fs"
import path from "path"
import { fileURLToPath } from "node:url"
import { convertZsmToVeraStream } from "./zsm2vera.mjs"

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, "..")
const gen = path.join(root, "generated")
const zsmPath = path.join(root, "assets", "othello.zsm")

// Walk the ZSM tick stream to find the tick that starts at the loop offset.
// Mirrors the loop-point mapping in tools/zsm2psg.py: ZSM delays advance the
// tick counter, and the first command at/after the loop offset starts the tick
// that playback resumes from.
// Also imported by tools/gen_pcm.mjs, which needs the same loop tick.
export const zsmLoopTick = (zsm) => {
  const loopOffset = zsm[3] | (zsm[4] << 8) | (zsm[5] << 16)
  if (!(loopOffset > 16 && loopOffset < zsm.length)) return 0
  let ptr = 16
  let tick = 0
  while (ptr < zsm.length) {
    if (ptr >= loopOffset) return tick
    const cmd = zsm[ptr++]
    if (cmd < 0x40) ptr += 1
    else if (cmd === 0x40) { const ext = zsm[ptr++]; ptr += ext & 0x3f }
    else if (cmd < 0x80) ptr += (cmd & 0x3f) * 2
    else if (cmd === 0x80) break
    else tick += cmd & 0x7f
  }
  return 0
}

// The stream is block aligned and each record fits inside one 512-byte block,
// so an MLI read of one block always yields whole records.  Find the byte
// offset of the first record group whose tick is at/after `targetTick`; this is
// where the player seeks on $FF, keeping the authored loop point instead of
// replaying the 25-second intro.
const findTickOffset = (data, targetTick) => {
  let tick = 0
  let pos = 0
  while (pos < data.length) {
    if (tick >= targetTick) return { offset: pos, tick }
    const b = data[pos]
    if (b === 0xff) break
    if (b < 0x80) { pos += 1; tick += b + 1; continue }
    if (b < 0xc0) { pos += 2; continue }
    if (b < 0xe0) { pos += 1 + ((b & 0x1f) + 1) * 2; continue }
    pos += 1
  }
  return { offset: 0, tick: 0 }
}

const main = () => {
  const zsm = fs.readFileSync(zsmPath)
  const result = convertZsmToVeraStream(zsm, { sourceName: "othello.zsm" })
  const { data, stats } = result

  const loopTick = zsmLoopTick(zsm)
  const loop = findTickOffset(data, loopTick)

  fs.mkdirSync(gen, { recursive: true })
  fs.writeFileSync(path.join(gen, "music.vzm"), data)
  fs.writeFileSync(path.join(gen, "music_vzm.h"),
    "/* Auto-generated by tools/gen_music.mjs - do not edit. */\n" +
    "#ifndef _MUSIC_VZM_H\n#define _MUSIC_VZM_H\n" +
    `#define MUSIC_VZM_SIZE   ${data.length}u\n` +
    `#define MUSIC_VZM_LOOP   ${loop.offset}u\n` +
    `#define MUSIC_VZM_TICKS  ${stats.ticks}u\n` +
    "#endif\n", "utf-8")

  const blocks = Math.ceil(data.length / 512)
  console.log(`  generated/music.vzm: ${data.length} bytes (${blocks} blocks, ` +
    `${stats.ticks} ticks = ${(stats.ticks / 60).toFixed(1)}s), ` +
    `loop@${loop.offset} (tick ${loopTick} -> group ${loop.tick}), ` +
    `PSG ${stats.psgKept}/${stats.psgWrites} writes, FM ${stats.fmKept}/${stats.fmWrites} writes`)
  if (loop.offset === 0) console.log("  WARNING: VZM loop offset not resolved, stream will loop from 0")
  /* The stream is addressed by a 16-bit block counter plus a 9-bit offset in
   * the player, and the loop point must fit a 16-bit byte offset. */
  if (blocks > 0xffff) throw new Error("VZM stream exceeds the 16-bit block counter")
  if (loop.offset > 0xffff) throw new Error("VZM loop offset exceeds 16 bits")
}

/* Run only when invoked directly: tools/gen_pcm.mjs imports zsmLoopTick. */
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
